function normalize(val: string): string {
  if (!val) return "";
  let clean = String(val).toUpperCase().trim();
  
  // Handle JSON structures if present
  if (clean.startsWith('{')) {
    try {
      const obj = JSON.parse(clean);
      if (obj.city) clean = obj.city.toUpperCase().trim();
      else if (obj.name) clean = obj.name.toUpperCase().trim();
    } catch (e) {}
  }

  return clean
    .replace(/^(KOTA|KABUPATEN|KAB|PROVINSI|KECAMATAN|KEC|KELURAHAN|KEL)\s+/g, "")
    .replace(/\s+(CITY|REGENCY|DISTRICT|VILLAGE)$/g, "")
    .replace(/[^A-Z0-9\s]/g, "")
    .trim();
}

export function getCityCode(val: string): string {
  if (!val) return "";
  const raw = String(val).trim().toUpperCase();
  
  // 1. Direct match with raw value (supports ID or full name)
  if (CITY_MAP[raw]) return CITY_MAP[raw];
  
  // 2. Normalized match
  const n = normalize(val);
  if (CITY_MAP[n]) return CITY_MAP[n];
  
  // 3. Fuzzy match
  const compactInput = n.replace(/\s+/g, "");
  if (compactInput.length > 3) {
    for (const [key, code] of Object.entries(CITY_MAP)) {
      const compactKey = key.replace(/\s+/g, "");
      if (compactInput === compactKey || compactInput.includes(compactKey) || compactKey.includes(compactInput)) {
        return code;
      }
    }
  }
  
  return "";
}
